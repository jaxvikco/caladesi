using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Caladesi.Runtime.Generators;

/// <summary>Generates Union&lt;T1..T8&gt;, the inline union types (<c>A | B | ...</c>) in Caladesi.Runtime.</summary>
[Generator]
public sealed class UnionGenerator : IIncrementalGenerator
{
    private const int MaxArity = 8;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx => ctx.AddSource("Union.g.cs", SourceText.From(Generate(), Encoding.UTF8)));
    }

    private static string Generate()
    {
        StringBuilder sb = new();
        _ = sb.AppendLine("// <auto-generated> by Caladesi.Runtime.Generators.UnionGenerator. </auto-generated>");
        _ = sb.AppendLine("#nullable enable");
        _ = sb.AppendLine("namespace Caladesi.Runtime;");
        _ = sb.AppendLine();
        for (int n = 2; n <= MaxArity; n++)
        {
            string ts = string.Join(", ", Enumerable(n, i => $"T{i}"));
            string name = $"Union<{ts}>";
            _ = sb.AppendLine("/// <summary>An inline union (<c>A | B | ...</c>): one value tagged with the 1-based index of its case.</summary>");
            _ = sb.AppendLine("[CaladesiUnion]");
            _ = sb.AppendLine($"public readonly struct {name} : System.IEquatable<{name}>");
            _ = sb.AppendLine("{");
            _ = sb.AppendLine("    /// <summary>1-based index of the case holding the value; 0 for the default (empty) union.</summary>");
            _ = sb.AppendLine("    public readonly int Tag;");
            _ = sb.AppendLine("    public readonly object? Value;");
            for (int i = 1; i <= n; i++)
            {
                _ = sb.AppendLine($"    public Union(T{i} value) {{ Tag = {i}; Value = value; }}");
            }

            for (int i = 1; i <= n; i++)
            {
                _ = sb.AppendLine($"    public static implicit operator {name}(T{i} value) => new(value);");
            }

            _ = sb.AppendLine($"    public bool Equals({name} other) => Tag == other.Tag && System.Collections.Generic.EqualityComparer<object?>.Default.Equals(Value, other.Value);");
            _ = sb.AppendLine($"    public override bool Equals(object? obj) => obj is {name} other && Equals(other);");
            _ = sb.AppendLine("    public override int GetHashCode() => System.HashCode.Combine(Tag, Value);");
            _ = sb.AppendLine("    public override string ToString() => Value?.ToString() ?? \"\";");
            _ = sb.AppendLine($"    public static bool operator ==({name} left, {name} right) => left.Equals(right);");
            _ = sb.AppendLine($"    public static bool operator !=({name} left, {name} right) => !left.Equals(right);");
            _ = sb.AppendLine("}");
            _ = sb.AppendLine();
        }
        return sb.ToString();
    }

    private static System.Collections.Generic.IEnumerable<string> Enumerable(int count, System.Func<int, string> f)
    {
        for (int i = 1; i <= count; i++)
        {
            yield return f(i);
        }
    }
}
